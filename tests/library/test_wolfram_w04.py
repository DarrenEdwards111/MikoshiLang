def T(src, text):
    """src must evaluate to exactly the string text."""
    return (src, Pred(lambda g, t=text: g == t, repr(text)))


def TS(src, text):
    """ToString[src] must be exactly text."""
    return T(f"ToString[{src}]", text)


def same_as(src, ref):
    return (src, ref)


def lines_at_most(n):
    return lambda g: isinstance(g, str) and all(len(s) <= n for s in g.split("\n"))


def well_formed_mathml(*tags):
    def p(g):
        try:
            d = xml.dom.minidom.parseString(g)
        except Exception:
            return False
        return d.documentElement.tagName == "math" and all(d.getElementsByTagName(t) for t in tags)
    return p


