"""Differential tests for coverage batch W04 (output forms, number formatting, layout wrappers, typesetting).

Reference values:

* number forms: the Wolfram Language reference pages (reference.wolfram.com/language/ref/NumberForm.html and the
  pages of ScientificForm, EngineeringForm, AccountingForm, PaddedForm, DecimalForm, PercentForm, BaseForm), and
  the output strings certified against Wolfram Mathematica in the Mathics3 test-suite (test/builtin/test_forms.py,
  test/format/format_tests-WMA.yaml), which record ``ToString[form[expr]]`` results;
* TeXForm/CForm/FortranForm: the WMA-certified TeX strings in format_tests-WMA.yaml (``a+b c``,
  ``\\frac{1}{\\frac{1}{\\frac{1}{a}+1}+1}``, ``\\int_a^{g(b)} F(x) \\, dx``, ``a_4``) and the documented C/Fortran
  conventions (``Power(x,2)``, ``x**2``, rationals as machine decimals);
* layout: Wolfram's OutputForm text for Grid and TableForm (``a   b\\n\\nc   d``: three spaces between columns, a
  blank line between rows), and properties checked here (alignment widths, element counts of Short skeletons,
  maximum line lengths of InsertLinebreaks/PageWidth).

MikoshiLang writes exponents on one line (``1.25×10^8``) where Wolfram's two-dimensional OutputForm puts the
exponent on the line above; the digits, signs, padding and separators are Wolfram's.
"""
