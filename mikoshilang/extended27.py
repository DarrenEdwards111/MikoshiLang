        ('ChokedFlowMach[M_]', lambda M: M >= 1),
        ('NormalShockMach[M1_, gamma_]', lambda M1, gamma: sqrt((1 + (gamma - 1)/2*M1**2)/(gamma*M1**2 - (gamma - 1)/2))),
        ('PressureRatioShock[M1_, gamma_]', lambda M1, gamma: 1 + 2*gamma/(gamma + 1)*(M1**2 - 1)),
        ('DensityRatioShock[M1_, gamma_]', lambda M1, gamma: ((gamma + 1)*M1**2)/((gamma - 1)*M1**2 + 2)),
        ('TemperatureRatioShock[M1_, gamma_]', lambda M1, gamma: (1 + 2*gamma/(gamma + 1)*(M1**2 - 1))*((gamma - 1)*M1**2 + 2)/((gamma + 1)*M1**2)),
        ('ObliqueShockAngle[M1_, beta_, gamma_]', lambda M1, beta, gamma: atan2(2*(M1**2*sin(beta)**2 - 1)*cos(beta), (M1**2*(gamma + cos(2*beta)) + 2))),
        ('ShockWaveAngle[M1_, theta_, gamma_]', lambda M1, theta, gamma: sp.Symbol('beta')),  # Iterative solution
        ('PrandtlMeyerAngle[M_, gamma_]', lambda M, gamma: sqrt((gamma + 1)/(gamma - 1))*atan2(sqrt((gamma - 1)/(gamma + 1)*(M**2 - 1)), 1) - atan2(sqrt(M**2 - 1), 1)),
        ('ExpansionWaveTurn[M1_, M2_, gamma_]', lambda M1, M2, gamma: sp.Symbol('nu2') - sp.Symbol('nu1')),
        ('RayleighFlowAero[M_, gamma_]', lambda M, gamma: (1 + gamma*M**2)/(1 + gamma)),
        ('FannoFlowAero[M_, gamma_]', lambda M, gamma: M*sqrt((gamma + 1)/(2 + (gamma - 1)*M**2))),
        ('AreaMachNumber[A_, A_star_, M_, gamma_]', lambda A, Astar, M, gamma: A/Astar - 1/M*((2 + (gamma - 1)*M**2)/(gamma + 1))**((gamma + 1)/(2*(gamma - 1)))),
        ('MassFlowRate[rho_, A_, v_]', lambda rho, A, v: rho*A*v),
        ('MassFlowRateChoked[A_, p0_, T0_, gamma_, R_]', lambda A, p0, T0, gamma, R: A*p0*sqrt(gamma/(R*T0))*(2/(gamma + 1))**((gamma + 1)/(2*(gamma - 1)))),
        ('NozzleThrust[mdot_, ve_, pe_, pa_, Ae_]', lambda mdot, ve, pe, pa, Ae: mdot*ve + (pe - pa)*Ae),
        ('ExitVelocity[gamma_, R_, T0_, pe_, p0_]', lambda gamma, R, T0, pe, p0: sqrt(2*gamma*R*T0/(gamma - 1)*(1 - (pe/p0)**((gamma - 1)/gamma)))),
        ('NozzleExpansionRatio[pe_, p0_]', lambda pe, p0: p0/pe),
        ('ConeDeCLaval[A_throat_, A_exit_]', lambda At, Ae: Ae/At),
        ('SupersonicNozzleArea[M_, A_star_, gamma_]', lambda M, Astar, gamma: Astar/M*((2 + (gamma - 1)*M**2)/(gamma + 1))**((gamma + 1)/(2*(gamma - 1)))),
        ('SubsonicDiffuserArea[M1_, M2_]', lambda M1, M2: M1/M2),
        ('InletPressureRecovery[p02_, p01_]', lambda p02, p01: p02/p01),
        ('RamEffect[v_]', lambda v: sp.Rational(1,2)*sp.Symbol('rho')*v**2),
        ('IntakeEfficiency[p02_, p0_]', lambda p02, p0: p02/p0),
        
        # ===== PROPULSION (30 functions) =====
        ('RocketEquation[delta_v_, ve_, m0_, mf_]', lambda dv, ve, m0, mf: dv - ve*log(m0/mf)),
        ('TsiolkovskyEquation[ve_, m0_, mf_]', lambda ve, m0, mf: ve*log(m0/mf)),
        ('ExhaustVelocity[Isp_, g0_]', lambda Isp, g0: Isp*g0),
        ('SpecificImpulseRocket[ve_, g0_]', lambda ve, g0: ve/g0),
        ('MassRatio[m0_, mf_]', lambda m0, mf: m0/mf),
        ('PropellantMassFraction[mp_, m0_]', lambda mp, m0: mp/m0),
        ('PayloadFraction[mpayload_, m0_]', lambda mpay, m0: mpay/m0),
        ('BurnTime[mp_, mdot_]', lambda mp, mdot: mp/mdot),
        ('ThrustRocket[mdot_, ve_, pe_, pa_, Ae_]', lambda mdot, ve, pe, pa, Ae: mdot*ve + (pe - pa)*Ae),
        ('ThrustCoefficient[T_, pc_, At_]', lambda T, pc, At: T/(pc*At)),
        ('CharacteristicVelocity[pc_, At_, mdot_]', lambda pc, At, mdot: pc*At/mdot),
        ('C_StarEfficiency[c_star_actual_, c_star_theoretical_]', lambda ca, ct: ca/ct),
        ('NozzleEfficiency[ve_actual_, ve_ideal_]', lambda vea, vei: vea/vei),
        ('CombustionEfficiency[c_star_actual_, c_star_theoretical_]', lambda ca, ct: ca/ct),
        ('ThrottleRatio[T_min_, T_max_]', lambda Tmin, Tmax: Tmin/Tmax),
        ('MixtureRatio[oxidizer_flow_, fuel_flow_]', lambda ox, fu: ox/fu),
        ('ChamberPressure[pc_]', lambda pc: pc),
        ('NozzleExpansionRatioOptimal[pa_, pc_, gamma_]', lambda pa, pc, gamma: ((gamma + 1)/2)**(gamma/(gamma - 1))*(pa/pc)**((gamma - 1)/gamma)),
        ('CombustionTemperature[Q_, cp_]', lambda Q, cp: Q/cp),
        ('AdiabaticFlameTemperature[reactants_, products_]', lambda r, p: sp.Symbol('T_flame')),
        ('TurbojetThrust[mdot_, ve_, v0_]', lambda mdot, ve, v0: mdot*(ve - v0)),
        ('TurbofanBypassRatio[m_bypass_, m_core_]', lambda mb, mc: mb/mc),
        ('OverallPressureRatio[p03_, p02_]', lambda p03, p02: p03/p02),
