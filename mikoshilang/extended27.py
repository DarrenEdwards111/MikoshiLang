        ('TakeoffDistance[v2_, acceleration_]', lambda v2, a: v2**2/(2*a)),
        ('LandingDistance[v_, deceleration_]', lambda v, a: v**2/(2*a)),
        ('TurnRadius[v_, phi_]', lambda v, phi: v**2/(sp.Symbol('g')*tan(phi))),
